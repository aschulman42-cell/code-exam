// Parse the model's "CLAIM: … ANCHORS: - file@func — element" reply into
// { prose, anchors:[{file,func,line,element}] }. Ported from the prototype's
// parseGeneratedClaim. Tolerant of leading bullets, em/en/double-dash element
// separators, and a `()` suffix on function names.
export function parseGeneratedClaim(text) {
  const t = String(text || '');
  const claimM = t.match(/CLAIM:\s*([\s\S]*?)(?:\n\s*ANCHORS:|$)/i);
  const prose = (claimM ? claimM[1] : t.split(/ANCHORS:/i)[0]).trim().replace(/\s+/g, ' ');
  const anchorsBlock = t.split(/ANCHORS:/i)[1] || '';
  const anchors = [];
  for (const ln of anchorsBlock.split(/\r?\n/)) {
    const m = ln.match(/^[\s\-*]+(.+)$/);
    if (!m) continue;
    const parts = m[1].trim().split(/\s[—–-]\s|\s--\s/);
    const ref = (parts[0] || '').trim().replace(/[`'"]/g, '');
    const element = (parts.slice(1).join(' ') || '').trim();
    let file = ref, func = '', line = 0, citedStart = 0, citedEnd = 0;
    // PARSE FROM THE RIGHT, not by part count.
    //
    // The old rule was `ref.split('@').length === 2`, which discarded the form
    // that carries BOTH a symbol and a line range:
    //
    //   src/core/ai-ml-detectors.js@_AIMLMethods::classify@L2150-2174
    //
    // Three parts failed the guard, the colon fallback did not match, func
    // stayed '' and groundAnchors dropped the citation as "no function name to
    // verify". MEASURED on the Gemini run over .CE_081726: 54 of 63 dropped
    // anchors (86%) were this branch, not the model -- and the rejected form is
    // STRICTLY MORE PRECISE than either form the prompt asks for.
    //
    // Counting parts also breaks on any path containing '@' (a real case --
    // issue-241-paste-safe-path-output round-trips @-in-path). Stripping an
    // @L<range> suffix and then splitting on the LAST '@' degrades gracefully
    // for both.
    // The @L<range> suffix is stripped ONLY when another '@' precedes it. The
    // DOC form `file@L1-20` has just one, and groundAnchors identifies it by
    // matching /^L(\d+)/ against `func` -- stripping there would empty func and
    // silently break every documentation citation in every existing artifact.
    // Caught by parsing all four forms before running the suite.
    let core = ref;
    const rangeM = core.indexOf('@') !== core.lastIndexOf('@')
      ? core.match(/@L(\d+)(?:-(\d+))?$/) : null;
    if (rangeM) {
      citedStart = Number(rangeM[1]);
      citedEnd = rangeM[2] ? Number(rangeM[2]) : citedStart;
      core = core.slice(0, core.length - rangeM[0].length);
    }
    const cut = core.lastIndexOf('@');
    if (cut > 0) { file = core.slice(0, cut).trim(); func = core.slice(cut + 1).trim().replace(/\(\)$/, ''); }
    else { file = core.trim(); const col = ref.match(/^(.+):(\d+)/); if (col) { file = col[1].trim(); line = Number(col[2]); } }
    if (file) anchors.push({ file, func, line, element, citedStart, citedEnd });
  }
  return { prose, anchors };
}

// Grounding pass: keep only cited anchors whose function resolves to a real
// function in the index (a SEPARATE anti-fabrication control from the caveat —
// the caveat governs how cited code is characterized; grounding governs whether
// the citation exists). The kept anchor carries the index's resolved path/lines,
// not the model's (possibly hallucinated) spelling.
export function groundAnchors(index, anchors) {
  const grounded = [];
  const dropped = [];
  for (const a of anchors || []) {
    // issue-286: a documentation line-range cite (`file@L<start>-<end>`)
    // grounds iff the file resolves to exactly one indexed file and the range
    // starts in bounds — the model cannot invent a doc path or a line range
    // (same anti-fabrication contract as function cites).
    const lm = a.func && a.func.match(/^L(\d+)(?:-(\d+))?$/);
    if (lm) {
      const start = Number(lm[1]);
      const end = lm[2] ? Number(lm[2]) : start;
      const hit = resolveIndexedFile(index, a.file);
      if (!hit || hit.ambiguous) {
        dropped.push({ ...a, reason: hit && hit.ambiguous ? 'cited doc path ambiguous in index' : 'cited doc file not in index' });
        continue;
      }
      const lines = index.fileLines.get(hit) || [];
      if (start < 1 || start > lines.length || end < start) {
        dropped.push({ ...a, reason: 'cited doc line range out of bounds' });
        continue;
      }
      grounded.push({ file: hit, func: '', start, end: Math.min(end, lines.length), element: a.element, kind: 'lines' });
      continue;
    }
    // A specific reason, not the catch-all. The old 'no function name to verify'
    // covered both "the model cited no symbol" and "the parser could not read
    // the ref" -- which is how 54 PARSER failures were reported as 54 MODEL
    // failures on the Gemini run.
    if (!a.func) {
      dropped.push({ ...a, reason: String(a.file || '').includes('@')
        ? 'anchor ref could not be parsed (unexpected @ structure)'
        : 'no function name to verify' });
      continue;
    }
    const matches = index.findFunctionMatches(a.func, a.file || null);
    if (!matches || matches.length === 0) {
      dropped.push({ ...a, reason: 'cited function not found in index' });
      continue;
    }
    const m = matches[0];
    // GROUND ON THE INDEX'S BOUNDS, never the model's -- unchanged, and the
    // anti-fabrication contract. The cited range rides along as a CHECK: when it
    // falls outside the resolved function, the symbol is real but the model
    // misplaced it. That is the "right file, right symbol, wrong lines" failure
    // asus-CC found by eye on the Gemma arm (#306); a parsed range makes it a
    // field instead of an observation.
    const rangeMismatch = !!(a.citedStart && (a.citedStart < m.start || a.citedStart > m.end));
    grounded.push({
      file: m.filepath, func: m.name, start: m.start, end: m.end,
      element: a.element, ambiguous: matches.length > 1,
      ...(a.citedStart ? { citedStart: a.citedStart, citedEnd: a.citedEnd || a.citedStart } : {}),
      ...(rangeMismatch ? { rangeMismatch: true } : {}),
    });
  }
  return { grounded, dropped };
}

// Reusable CLAIM-CHART formatter (#284 --pseudo-claims-chart): render the claim
// AS WRITTEN — a preamble row plus one row per element/step of the claim prose
// (elements are semicolon-delimited; the drafter is instructed to write that
// way, so it works model-independently — Claude's coarse anchors or Gemini's
// fine ones alike). Each grounded anchor's cite is attached to the element whose
// text it most overlaps; elements with no confident cite are left blank
// (cite→element alignment is deliberately approximate for now). Kept
// standalone/exported so claim-search / claim-analyze can reuse the same
// element→evidence view rather than reinventing it.
// A CLAIM IS ONE SENTENCE, so it survives being written as one line, and one
// line per claim is the format every downstream stage already reads. Whitespace
// is collapsed because the drafter hard-wraps prose and the wrapping carries no
// meaning -- the element boundaries live in the punctuation, not the newlines.
export function claimToLine(prose) {
  return String(prose || '').replace(/\s+/g, ' ').trim();
}

// The answer key. Written as a SIDECAR rather than inline so the claims file
// stays feedable to --synonymize unchanged, and as JSON rather than re-parsed
// out of the Markdown later so there is exactly one source of truth for what
// was cited.
//
// Only GROUNDED anchors travel: each was resolved against the index and the
// ungrounded ones dropped (see verifyAnchors). `dropped` is carried too, with
// its reason, because a key that silently omits what the drafter cited but CE
// could not find would overstate how complete it is.
export function buildAnchorSidecar(groups, drafts, meta = {}) {
  const claims = [];
  drafts.forEach((d, i) => {
    if (!d || d.error || !d.prose) return;
    claims.push({
      n: claims.length + 1,
      groupN: i + 1,
      label: groups[i] ? groups[i].label || '' : '',
      claim: claimToLine(d.prose),
      // Carried so a downstream consumer (HOF-c scoring, --claims-loop) cannot
      // mistake a severed anchor list for "the drafter cited nothing".
      ...(d.truncated ? { truncated: true } : {}),
      // Recorded so a scorer can refuse to compare a rewritten claim whose
      // element count no longer matches its key, instead of pairing element 4
      // against element 5 and reporting a plausible wrong number.
      elements: splitClaimElements(claimToLine(d.prose)),
      grounded: (d.grounded || []).map((a) => ({
        file: a.file, func: a.func || '', start: a.start, end: a.end,
        kind: a.kind || 'func', element: a.element || '',
        ...(a.ambiguous ? { ambiguous: true } : {}),
      })),
      dropped: (d.dropped || []).map((a) => ({
        file: a.file, func: a.func || '', reason: a.reason || '',
      })),
    });
  });
  return {
    format: 'ce-pseudo-claim-anchors',
    version: 1,
    note: 'GROUNDED means the citation resolved to a real symbol in the index. This key records'
      + ' what the DRAFTING MODEL cited, verified to resolve — not what a practitioner would cite.',
    ce: meta.ceVersion || '', generated: meta.generatedAt || '', command: meta.argv || '',
    truncated: claims.filter((c) => c.truncated).length,
    claims,
  };
}

export function writeClaimsOnly(fpath, groups, drafts, meta = {}) {
  const sidecar = buildAnchorSidecar(groups, drafts, meta);
  const skipped = drafts.filter((d) => !d || d.error || !d.prose).length;
  const header = [
    '# Pseudo-claims — illustrative drafting exercise, NOT legal analysis.',
    '# NOT patent claims. Generated for retrieval testing; do not file, quote, or rely on.',
    // Read back by --synonymize, so this file needs no flag to be understood.
    '# Format:     one claim per line',
    `# Claims:     ${sidecar.claims.length}${skipped ? ` (${skipped} skipped — draft failed)` : ''}`,
    `# Anchors:    ${sidecar.claims.reduce((n, c) => n + c.grounded.length, 0)} grounded, in ${fpath}.anchors.json`,
    ...(sidecar.truncated ? [`# TRUNCATED:  ${sidecar.truncated} claim(s) hit the output budget` + ` - incomplete text, missing anchors; see .anchors.json for which`] : []),
    `# CE:         ${meta.ceVersion || ''}`,
    `# Generated:  ${meta.generatedAt || ''}`,
    `# Command:    ${meta.argv || ''}`,
  ].join('\n');
  const body = sidecar.claims.map((c) => c.claim).join('\n');
  const sidecarPath = `${fpath}.anchors.json`;
  try {
    fs.writeFileSync(fpath, `${header}\n${body}\n`, 'utf8');
    fs.writeFileSync(sidecarPath, `${JSON.stringify(sidecar, null, 2)}\n`, 'utf8');
  } catch (e) {
    return { ok: false, error: e.message };
  }
  return {
    ok: true, claims: sidecar.claims.length, skipped, sidecar: sidecarPath,
    anchors: sidecar.claims.reduce((n, c) => n + c.grounded.length, 0),
  };
}

export function formatClaimChart(prose, grounded) {
  const esc = (s) => String(s).replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
  const cite = (a) => a.kind === 'lines'
    ? `\`${a.file}@L${a.start}-${a.end}\` (doc)`
    : `\`${a.file}@${a.func}\`${a.start ? ` (L${a.start}-${a.end})` : ''}`;
  const kw = (s) => new Set(String(s).toLowerCase().match(/[a-z][a-z0-9_]{3,}/g) || []);
  // Parse claim prose: preamble = text through the first ':'; elements = the
  // remainder split on ';' (standard method-claim form).
  const text = String(prose || '').trim();
  const ci = text.indexOf(':');
  const preamble = ci >= 0 ? text.slice(0, ci + 1).trim() : '';
  const body = ci >= 0 ? text.slice(ci + 1) : text;
  const elements = body.split(';').map((e) => e.trim().replace(/[.\s]+$/, '')).filter(Boolean);
  // Best-effort: attach each grounded cite to the element it most overlaps.
  const elemKw = elements.map(kw);
  const elemCites = elements.map(() => []);
  const unmatched = [];
  for (const a of grounded || []) {
    const aw = kw(a.element || '');
    let best = -1, score = 0;
    for (let i = 0; i < elemKw.length; i += 1) {
      let s = 0; for (const w of aw) if (elemKw[i].has(w)) s += 1;
      if (s > score) { score = s; best = i; }
    }
    const c = cite(a);
    if (best >= 0 && score >= 1) { if (!elemCites[best].includes(c)) elemCites[best].push(c); }
    else unmatched.push(c);
  }
  const lines = ['| # | Claim element / step | Cited code |', '|---|---|---|'];
  let n = 0;
  if (preamble) { n += 1; lines.push(`| ${n} | ${esc(preamble)} | _Preamble_ |`); }
  for (let i = 0; i < elements.length; i += 1) {
    n += 1;
    lines.push(`| ${n} | ${esc(elements[i])} | ${elemCites[i].join('<br>')} |`);
  }
  if (!preamble && !elements.length) lines.push('| — | _(no claim text to chart)_ | — |');
  if (unmatched.length) lines.push('', `_Grounded cite(s) not matched to a specific element: ${unmatched.join(', ')}._`);
  return lines;
}

/**
 * `--pseudo-claims --candidates <path>` (#284 B1): emit an UNRANKED mechanism
 * candidate anchors.lst via the deterministic grouper (mechanism-grouper.js),
 * instead of drafting. `--group-by concept` selects the token-only baseline;
 * `--file-seed` enables the opt-in residual file seed. `--ground-truth <gt.lst>`
 * scores the candidates' recall/precision against a hand-authored anchor set (a
 * dev path) instead of writing candidates. This is the front half of the pipeline
 * whose ranked one-command form is the future `--pseudo-claims --auto` (B2).
 */
export async function doEmitCandidates(index, args) {
  const indexName = String(args.index_path || '').replace(/[\\/]+$/, '').split(/[\\/]/).pop() || '?';
  let result;
  try {
    result = groupMechanisms(index, {
      indexName,
      mode: args.group_by === 'concept' ? 'concept' : 'multi',
      fileSeed: !!args.file_seed,
      useDocs: !!args.use_docs,
      catalogSeed: !!args.catalog_seed,
      literalSeed: !!args.literal_seed,
      bodyMatchSeed: !!args.body_match_seed,
      includeVendored: !!args.include_vendored,
      // 0 disables splitting and reproduces pre-split candidate files exactly,
      // so artifacts generated before this landed stay reproducible.
      ...(args.group_max != null ? { groupMax: args.group_max || Infinity } : {}),
    });
  } catch (e) {
    console.error(`--pseudo-claims --candidates: grouping failed: ${e.message}`);
    process.exitCode = 1;
    return;
  }

  // --ground-truth: score instead of emit (dev path).
  if (args.ground_truth) {
    let gtText;
    try { gtText = fs.readFileSync(args.ground_truth, 'utf8'); }
    catch (e) { console.error(`--ground-truth: cannot read '${args.ground_truth}': ${e.message}`); process.exitCode = 1; return; }
    const s = scoreGrouping(index, result, gtText);
    console.log(`# mechanism-grouper score  index=${indexName}  group-by=${result.mode}  candidates=${result.groups.length} groups`);
    console.log(`# ground-truth: ${s.gtGroups} groups, ${s.scored} scored  avgRecall=${s.avgRecall.toFixed(2)} avgPrecision=${s.avgPrecision.toFixed(2)}`);
    for (const r of s.rows) {
      if (r.note) { console.log(`   ${r.label}: ${r.note}`); continue; }
      console.log(`   ${r.recall.toFixed(2)}R ${r.precision.toFixed(2)}P  ${r.together}/${r.resolved} together, in a cluster of ${r.clusterSize}  — ${r.label.slice(0, 58)}`);
    }
    return;
  }

  const outPath = (args.candidates && args.candidates !== '-' && args.candidates !== '.') ? args.candidates : null;

  // --rank (#284 ranker Phase 0): score each candidate with a bounded LLM
  // exploration-PRIORITY verdict, then emit the candidates ANNOTATED and sorted
  // highest-priority first. Still observe-only — the ANCHORS are identical; only
  // the `# ` headers gain a [P..] tag and the group order reflects priority.
  // Nothing is dropped or merged (that is Phase 1 / --auto). The pcrun soak
  // measures these verdicts.
  if (args.rank) {
    const model = resolveModel(args);
    if (!model || model.kind === 'error') {
      console.error(`--rank needs a model: pass --llm <provider> or --model <gguf> (${model?.error || 'none configured'}).`);
      process.exitCode = 1; return;
    }
    let drafter;
    try { drafter = makeDrafter(model, 0.2); }
    catch (e) { console.error(`--rank: ${e.message}`); process.exitCode = 1; return; }
    // pseudo-claims-cost-guard: project the comparative-ranking spend from the
    // ACTUAL batch prompts (cheap string builds), +30% for the playoff rounds
    // (the ffmpeg 244-group run's two playoff rounds added ~30%). Gate before
    // the first API call; --force / CE_CLAIMS_COST_GUARD override.
    {
      const calls = [];
      for (let i = 0; i < result.groups.length; i += 20) {
        const batch = result.groups.slice(i, i + 20);
        const { sys, user } = buildBatchPrompt(batch, index, {});
        calls.push({ inChars: (sys.length + user.length) * 1.3, outTokens: Math.min(2000, 120 + batch.length * 60) * 1.3 });
      }
      if (!claimsCostGate(model, calls, `rank ${result.groups.length} candidates, ${Math.ceil(result.groups.length / 20)} batches + playoff`, args)) return;
    }
    resetCloudUsage();
    const mlabel = model.label || model.model || 'model';
    console.error(`# mechanism-ranker: scoring ${result.groups.length} candidates via ${mlabel}…`);
    const scored = await rankCandidates(result.groups, index, drafter, {});
    const rankCost = actualCostLine(model);
    if (rankCost) console.error(rankCost);
    const vByLabel = new Map(scored.map((s) => [s.label, s.verdict]));
    const sorted = [...result.groups].sort((a, b) => ((vByLabel.get(b.label)?.priority ?? -1) - (vByLabel.get(a.label)?.priority ?? -1)));
    const ranked = scored.filter((s) => s.verdict).length;
    const caveat = [
      '# ILLUSTRATIVE claim-candidate ranking — a FAST, SURFACE heuristic to suggest where to',
      '# look FIRST, NOT legal analysis and NOT a judgment of novelty, importance, or worth.',
      '# A low P-score means only that a cluster RESEMBLES a common pattern or borrowed code at a',
      "# glance — NOT that it lacks value or novelty. Routine-looking code can be the crux, and",
      "# the user's considered judgment governs. Verify independently; not an admission about",
      '# any code or claim.',
      '#',
    ];
    const lines = [...caveat, `# mechanism-ranker  index=${indexName}  group-by=${result.mode}  ${result.groups.length} groups — RANKED by ${mlabel} (observe-only; anchors unchanged; ${ranked}/${scored.length} scored) — first-pass exploration priority; tag is [P0-3 signal/fold — what it resembles]`];
    for (const g of sorted) {
      const v = vByLabel.get(g.label);
      const tag = v ? `  [P${v.priority} ${v.signal}/${v.fold}${v.note ? ' — ' + v.note : ''}]` : '  [unscored]';
      const purpose = harvestPurpose(index, g.label, g.members);
      lines.push('', `# ${g.label}  (${g.members.length} fns)${tag}${purpose ? '  — ' + purpose : ''}`);
      // issue-289-doc-anchor-enrichment: doc anchors first (budget-first placement).
      if (args.doc_anchors) for (const d of docAnchorsForGroup(index, g.label, g.members)) lines.push(d);
      for (const f of g.members) { const spec = f.name.includes('@') ? f.bare : f.name; lines.push(`${f.file}@${spec}`); }
    }
    const rankedText = lines.join('\n') + '\n';
    if (outPath) {
      fs.writeFileSync(outPath, rankedText, 'utf8');
      console.error(`# wrote ${result.groups.length} RANKED candidate group(s) to ${outPath}  (${indexName}, ${ranked}/${scored.length} scored by ${mlabel})`);
    } else {
      process.stdout.write(rankedText);
    }
    reportEchoes(sorted);
    return;
  }

  const text = formatAnchors(result, {
    indexName,
    minComm: GROUPER_DEFAULTS.minComm,
    purposeFor: (label, members) => harvestPurpose(index, label, members),
    ...(args.doc_anchors ? { docAnchorsFor: (label, members) => docAnchorsForGroup(index, label, members) } : {}),
  });
  if (outPath) {
    fs.writeFileSync(outPath, text, 'utf8');
    console.error(`# wrote ${result.groups.length} candidate group(s) to ${outPath}  (${indexName}, group-by=${result.mode}, unranked; pre-filtered ${result.noiseFiles} noise files / ${result.noiseFns} fns)`);
  } else {
    process.stdout.write(text);
  }
  reportEchoes(result.groups);
}

// grouper-echo-flag-fold Phase 1: one stderr line per detected echo pair at
// emit time, so .lst-stage curation sees them before any drafting spend.
function reportEchoes(groups) {
  for (const p of echoPairs(groups)) {
    console.error(`# echo: ${p.host.label} ~ ${p.echo.label} (${String(p.file).split('!').pop()})`);
  }
}

/**
 * Handle `--pseudo-claims <anchors>`. Partitions anchors into groups (one
 * pseudo-claim each), resolves + extracts each, assembles a bounded evidence
 * pack per group, then either prints the packs (--dry-run / no model) or drafts
 * one grounded pseudo-claim per pack. Sets process.exitCode on error.
 */
export async function doPseudoClaims(index, args) {
  if (args.candidates || args.ground_truth || args.rank) { await doEmitCandidates(index, args); return; }
  const spec = args.pseudo_claims;

  let groups;
  try {
    groups = collectAnchorGroups(spec);
  } catch (e) {
    console.error(`--pseudo-claims: could not read anchor list '${String(spec).slice(1)}': ${e.message}`);
    process.exitCode = 1;
    return;
  }
  if (groups.length === 0) {
    console.error('--pseudo-claims: no anchors given. Provide "file@func;file@func" or @anchors.lst (one file@func per line; "# Label" lines separate claims).');
    process.exitCode = 1;
    return;
  }

  if (Number.isNaN(parseMinRank(args.min_rank))) {
    console.error(`--min-rank: expected 0-3 or P0-P3 (got '${args.min_rank}').`);
    process.exitCode = 1;
    return;
  }
  const totalGroups = groups.length;
  const mr = filterGroupsByMinRank(groups, args.min_rank);
  groups = mr.groups;
  if (mr.dropped) {
    console.error(`# --min-rank P${mr.floor}: drafting ${groups.length} of ${totalGroups} candidate group(s); ${mr.dropped} below the floor skipped.`);
    console.error('Tip: --min-rank 0 drafts every group; --min-rank 3 only the top tier.');
  }
  if (groups.length === 0) {
    console.error(`--pseudo-claims: no groups at or above --min-rank P${mr.floor}; nothing to draft (Tip: lower --min-rank).`);
    process.exitCode = 1;
    return;
  }
  // Selection disclosure for the artifact intro — a chart should say what it excluded.
  const selNote = mr.dropped ? ` ${groups.length} of ${totalGroups} candidate group(s) drafted (--min-rank P${mr.floor}).` : '';

  const multi = groups.length > 1;

  // Resolve + pack each group.
  const sections = [];
  let totalResolved = 0;
  let totalProblems = 0;
  groups.forEach((g, gi) => {
    const { resolved, problems } = resolveGroup(index, g);
    const { pack, truncatedAnchors, droppedForBudget } = buildPack(resolved);
    sections.push({ label: g.label, purpose: g.purpose || '', fold: g.fold || null, priority: g.priority ?? null, groupNum: gi + 1, resolved, problems, pack, truncatedAnchors, droppedForBudget });
    totalResolved += resolved.length;
    totalProblems += problems.length;
  });

  // Report dropped anchors to stderr (grouped when there are multiple claims),
  // so stdout stays a clean artifact.
  if (totalProblems) {
    console.error(`\n${totalProblems} anchor(s) dropped (did not resolve to a real function):`);
    for (const s of sections) {
      if (!s.problems.length) continue;
      if (multi) console.error(`  [${s.label || `group ${s.groupNum}`}]`);
      for (const p of s.problems) console.error(`  ✗ ${p.spec} — ${p.reason}`);
    }
    console.error('');
  }
  if (totalResolved === 0) {
    console.error('--pseudo-claims: no anchors resolved to real functions; nothing to draft.');
    process.exitCode = 1;
    return;
  }

  const withAnchors = sections.filter((s) => s.resolved.length);
  const model = resolveModel(args);
  if (model && model.kind === 'error') {
    console.error(`--pseudo-claims: ${model.error}`);
    process.exitCode = 1;
    return;
  }
  const dryRun = !!args.dry_run || !model;
  // Evidence pack in the OUTPUT artifact: absent by default (keeps --pseudo-claims
  // lean); shown on --dry-run (the pack IS that mode's deliverable) or with
  // --include-evidence-pack. The model ALWAYS receives the pack as INPUT
  // (buildPack -> drafter, below) — this flag only controls the artifact.
  const showPack = dryRun || !!args.include_evidence_pack;
  const chartMode = !dryRun && !!args.pseudo_claims_chart;
  const temperature = args.temperature ?? 0;
  const modelDesc = !model ? '' : model.kind === 'gguf' ? `local GGUF ${model.modelPath}` : `${model.label} (${model.model})`;

  // If drafting, build the drafter up front (the air-gap gate + key check may
  // throw here).
  let drafter = null;
  if (!dryRun) {
    try {
      drafter = makeDrafter(model, temperature);
    } catch (e) {
      console.error(`--pseudo-claims: ${e.message}`);
      process.exitCode = 1;
      return;
    }
    // pseudo-claims-cost-guard: packs are already built (s.pack), so the
    // drafting projection is exact — pack + system prompt in, 900 out per
    // claim. Gate before the first API call.
    const calls = withAnchors.map((s) => ({
      inChars: PSEUDO_CLAIM_GENERATE_SYS.length + 200 + (s.pack ? s.pack.length : 0),
      outTokens: 900,
    }));
    if (!claimsCostGate(model, calls, `${withAnchors.length} drafts`, args)) return;
    resetCloudUsage();
    process.stderr.write(`Drafting ${withAnchors.length} pseudo-claim(s) via ${modelDesc}…\n`);
  }

  // Draft each group's claim (sequentially; a shared GGUF session is not
  // concurrent-safe, and endpoints are gentler one at a time).
  const drafts = [];
  if (!dryRun) {
    for (let i = 0; i < withAnchors.length; i++) {
      const s = withAnchors[i];
      try {
        // Label + purpose as ONE line (separating them weakened both — the
        // ranker-purpose-signal lesson); triage annotations already stripped.
        const mech = s.label ? `${s.label}${s.purpose ? ' — ' + s.purpose : ''}` : '';
        const intent = mech ? `MECHANISM: ${mech}\n\n` : '';
        const raw = await drafter(PSEUDO_CLAIM_GENERATE_SYS, `${intent}CODE:\n${s.pack}`, PSEUDO_CLAIM_MAX_OUTPUT_TOKENS);
        // Read the flag IMMEDIATELY after the await -- it carries THIS call's
        // verdict (draftCloud clears it on entry) and drafting is sequential.
        const truncated = wasLastDraftTruncated();
        const { prose, anchors } = parseGeneratedClaim(raw);
        const { grounded, dropped } = groundAnchors(index, anchors);
        drafts.push({ prose, grounded, dropped, truncated });
        process.stderr.write(`  claim ${i + 1}/${withAnchors.length}: ${grounded.length} grounded anchor(s)${dropped.length ? `, ${dropped.length} ungrounded dropped` : ''}`
          + `${truncated ? ' - TRUNCATED by the output budget; ANCHORS block incomplete' : ''}\n`);
      } catch (e) {
        drafts.push({ error: e.message });
        process.stderr.write(`  claim ${i + 1}/${withAnchors.length}: draft failed — ${e.message}\n`);
      }
    }
    // Never silent: 16 anchor-less claims sat in a file for a day looking like
    // ordinary output because nothing said the drafts had been cut off.
    const tline = truncationLine();
    if (tline) process.stderr.write(tline.replace(/^# /, '[pseudo-claims] ') + '\n');
    const draftCost = actualCostLine(model);
    if (draftCost) process.stderr.write(draftCost + '\n');
  }

  // Build the artifact: Block A once, then one section per non-empty group.
  const out = [];
  out.push(PSEUDO_CLAIM_CAVEAT_A);
  out.push('');
  if (dryRun) {
    out.push(`_Deterministic scaffold (dry run): below is the exact, size-capped evidence pack a model would be handed — one per pseudo-claim (${withAnchors.length}).${selNote} To draft, pass \`--model <gguf>\` or set \`CE_OPENAI_API_URL\` (drop \`--dry-run\`)._`);
  } else {
    out.push(`_Drafted from ${withAnchors.length} evidence pack(s) via ${modelDesc}.${selNote} Each claim's cited anchors are **grounded** — verified to resolve to a real function in the index; ungrounded citations are dropped.${showPack ? ' The evidence pack the draft was grounded in follows each claim.' : ' Pass --include-evidence-pack to append each claim\'s evidence pack.'}_`);
  }
  out.push('');

  // grouper-echo-flag-fold Phase 1: detect echo pairs across the chart's
  // groups by shared dominant file (resolved anchors carry filepath; doc
  // anchors never count). echoByIdx: section index -> {hostN, hostLabel, file}
  // for the SMALLER group of each pair — flags point at the larger.
  const echoByIdx = new Map();
  {
    const wrapped = withAnchors.map((s, i) => ({ __i: i, label: s.label, members: s.resolved }));
    for (const p of echoPairs(wrapped)) {
      echoByIdx.set(p.echo.__i, { hostN: p.host.__i + 1, hostLabel: p.host.label, file: String(p.file).split('!').pop() });
    }
  }

  // chart-toc-rank-display: a multi-claim chart opens with a rank-and-name
  // contents table (drafted preambles as names; labels alone in dry-run).
  if (withAnchors.length >= 2) {
    const rows = withAnchors.map((s, i) => ({
      n: i + 1,
      label: s.label,
      priority: s.priority,
      preamble: !dryRun && drafts[i] && drafts[i].prose ? claimPreambleSnippet(drafts[i].prose) : '',
      echoOf: echoByIdx.get(i) || null,
    }));
    for (const ln of formatChartToc(rows)) out.push(ln);
  }

  withAnchors.forEach((s, i) => {
    const label = s.label ? ` — ${s.label}` : '';
    const rankSuffix = s.priority != null ? `  (P${s.priority})` : '';
    out.push(`## Pseudo-claim ${i + 1}${label}${rankSuffix}`);
    out.push('');
    // #291 Part C: a split-flagged group is over-broad by the ranker's own
    // verdict — disclose that this claim may cover only a slice of it.
    if (s.fold === 'split') {
      out.push('_The ranker marked this group `split` (over-broad); this claim may cover only a slice of it._');
      out.push('');
    }
    const echo = echoByIdx.get(i);
    if (echo) {
      out.push(`_Likely echo: this group shares its dominant file (\`${echo.file}\`) with Pseudo-claim ${echo.hostN} — probably the same mechanism claimed from a different seed._`);
      out.push('');
    }

    if (!dryRun) {
      const d = drafts[i];
      out.push(PSEUDO_CLAIM_CAVEAT_B);
      out.push('');
      if (d.error) {
        out.push(`_Draft failed: ${d.error}. The evidence pack is below for reference._`);
        out.push('');
      } else {
        out.push(d.prose || '_(model produced no claim text)_');
        // A truncated draft must not read as a finished claim. The mark goes in
        // the ARTIFACT, not just stderr: stderr is gone by the time anyone reads
        // the file, which is how 16 anchor-less claims passed for ordinary output.
        if (d.truncated) {
          out.push('');
          out.push('_**TRUNCATED** - this draft hit the output budget and stops mid-text.'
            + ' Its `ANCHORS:` block was never emitted, so the cited-anchor list below is'
            + ' incomplete or empty. This is a CE budget limit, not a finding about the code._');
        }
        out.push('');
        if (chartMode) {
          out.push(`### Claim chart (${d.grounded.length} grounded cite${d.grounded.length === 1 ? '' : 's'}${d.dropped.length ? `, ${d.dropped.length} ungrounded dropped` : ''})`);
          out.push('');
          for (const ln of formatClaimChart(d.prose, d.grounded)) out.push(ln);
        } else {
          out.push(`### Cited anchors (${d.grounded.length} grounded${d.dropped.length ? `, ${d.dropped.length} ungrounded dropped` : ''})`);
          out.push('');
          for (const a of d.grounded) {
            out.push(a.kind === 'lines'
              ? `- \`${a.file}@L${a.start}-${a.end}\` — documentation excerpt${a.element ? ` — ${a.element}` : ''}`
              : `- \`${a.file}@${a.func}\` — L${a.start}-${a.end}${a.element ? ` — ${a.element}` : ''}`);
          }
          if (!d.grounded.length) out.push('- _(no cited anchor resolved to a real function)_');
        }
        if (d.dropped.length) {
          out.push('');
          out.push(`_Dropped (cited but not found in index): ${d.dropped.map((a) => `\`${a.file}@${a.func || '?'}\``).join(', ')}._`);
        }
        out.push('');
      }
      if (!showPack) {
        const disc = packDisclosure(s);
        if (disc) { out.push(disc); out.push(''); }
      }
      if (showPack) out.push('### Evidence pack (the code this draft was grounded in)');
    } else {
      out.push(`### Anchors (${s.resolved.length})`);
      out.push('');
      for (const a of s.resolved) {
        out.push(a.kind === 'lines'
          ? `- \`${a.filepath}@L${a.start}-${a.end}\` — documentation excerpt (${a.end - a.start + 1} lines)`
          : `- \`${a.filepath}@${a.name}\` — L${a.start}-${a.end} (${a.end - a.start + 1} lines)`);
      }
      if (showPack) out.push('', '### Evidence pack');
    }

    if (showPack) {
      out.push('');
      if (s.truncatedAnchors.length) {
        out.push(`_Truncated to the ${PACK_PER_ANCHOR_CHARS}-char per-anchor cap: ${s.truncatedAnchors.map((x) => `\`${x}\``).join(', ')}._`);
        out.push('');
      }
      if (s.droppedForBudget) {
        out.push(`_${s.droppedForBudget} anchor(s) omitted after the ${PACK_TOTAL_CHARS}-char per-claim pack budget was reached._`);
        out.push('');
      }
      out.push(s.pack);
      out.push('');
    }
  });
  out.push(PSEUDO_CLAIM_CAVEAT_C);

  const text = out.join('\n') + '\n';

  // --claims-only: the MACHINE-READABLE SIBLING of the artifact above.
  //
  // The artifact is written for a human reader — a legal caveat block, a
  // contents list, anchor tables, evidence-pack notes. Feeding it to the next
  // stage does not work and fails expensively: `--synonymize @<artifact>` split
  // it into 171 "elements" and began rewriting the disclaimer one model call at
  // a time. The fix belongs HERE, in the producer, not in a consumer taught to
  // reverse-engineer a report whose layout is free to change.
  if (args.claims_only) {
    if (dryRun) {
      console.error('--claims-only: nothing to write — --dry-run resolves anchors but drafts no claims.');
      process.exitCode = 1;
      return;
    }
    const written = writeClaimsOnly(args.claims_only, withAnchors, drafts, {
      argv: process.argv.slice(1).join(' '),
      ceVersion: readCeVersion(),
      generatedAt: new Date().toISOString(),
    });
    if (!written.ok) {
      console.error(`--claims-only: ${written.error}`);
      process.exitCode = 1;
      return;
    }
    console.log(`Wrote ${written.claims} claim(s) to ${args.claims_only}`
      + ` and ${written.anchors} grounded anchor(s) to ${written.sidecar}.`
      + (written.skipped ? ` ${written.skipped} claim(s) skipped (draft failed).` : ''));
  }

  // Emit to stdout or --pseudo-out <file>.
  if (args.pseudo_out) {
    try {
      fs.writeFileSync(args.pseudo_out, text, 'utf8');
      console.log(`Wrote pseudo-claims artifact to ${args.pseudo_out} — ${withAnchors.length} pseudo-claim(s), ${totalResolved} anchor(s)${totalProblems ? `, ${totalProblems} dropped` : ''}${dryRun ? ' (dry run — no model draft)' : ''}.`);
    } catch (e) {
      console.error(`--pseudo-claims: could not write '${args.pseudo_out}': ${e.message}`);
      process.exitCode = 1;
    }
  } else {
    process.stdout.write(text);
  }
}
