// Evidence-pack size bounds (per group, shared so the pack the user eyeballs in
// dry-run is exactly what the model receives).
export const PACK_PER_ANCHOR_CHARS = 8000;
export const PACK_TOTAL_CHARS = 24000;

// A fence longer than the longest backtick run in `body` — CE's own source is
// full of backtick template literals, so a fixed ``` fence would break out of
// the block mid-body.
function fenceFor(body) {
  const longest = (String(body).match(/`+/g) || []).reduce((n, s) => Math.max(n, s.length), 0);
  return '`'.repeat(Math.max(3, longest + 1));
}

// Partition the command value into anchor GROUPS (one group == one pseudo-claim).
//   - inline "a@f;b@g"  -> a single group (label null)
//   - "@anchors.lst"    -> one-or-more groups; a "# Label" line starts a new
//                          group and names it; anchors before any header form an
//                          implicit first group; blank lines ignored.
// Headers are parsed via parseAnchorHeader (the grouper emit's inverse), so a
// group carries a CLEAN {label, purpose} — the `(N fns)` count, `[P…]` priority
// tag, and ranker note are stripped rather than riding into the MECHANISM hint
// and the output heading. The hint itself is KEPT (label + purpose); only the
// triage annotations are removed. Priority is parsed but deliberately unused
// here (a later --auto phase may fold P0s). Exported for tests.
export function collectAnchorGroups(spec) {
  if (!spec || !spec.startsWith('@')) {
    const specs = String(spec || '').split(';').map((s) => s.trim()).filter(Boolean);
    return specs.length ? [{ label: null, purpose: '', specs }] : [];
  }
  const listPath = spec.slice(1);
  const text = fs.readFileSync(listPath, 'utf8'); // caller catches ENOENT
  const groups = [];
  let cur = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith('#')) {
      const { label, purpose } = parseAnchorHeader(line);
      cur = { label: label || null, purpose: purpose || '', specs: [] };
      groups.push(cur);
      continue;
    }
    if (!cur) { cur = { label: null, purpose: '', specs: [] }; groups.push(cur); }
    cur.specs.push(line);
  }
  return groups.filter((g) => g.specs.length);
}

// Resolve one group's anchor specs to real functions (the existence check the
// file-level prototype lacked — it cited fragments like strRe.exec(body)).
function resolveGroup(index, group) {
  const resolved = [];
  const problems = [];
  for (const a of group.specs) {
    const { fileHint, funcName } = parseFuncSpec(a);
    const matches = index.findFunctionMatches(funcName, fileHint);
    if (!matches || matches.length === 0) {
      problems.push({ spec: a, reason: 'no function in the index resolves to this anchor' });
      continue;
    }
    if (matches.length > 1) {
      const opts = matches.slice(0, 5).map((m) => `${m.filepath}@${m.name} (L${m.start}-${m.end})`).join('; ');
      const more = matches.length > 5 ? `; …+${matches.length - 5} more` : '';
      problems.push({ spec: a, reason: `ambiguous — ${matches.length} functions match; use an exact file@func (e.g. ${opts}${more})` });
      continue;
    }
    const m = matches[0];
    const source = index.getFunctionSource(m.filepath, m.name);
    if (!source) {
      problems.push({ spec: a, reason: 'matched, but source could not be extracted (file content not loaded in this index)' });
      continue;
    }
    resolved.push({ spec: a, filepath: m.filepath, name: m.name, start: m.start, end: m.end, source });
  }
  return { resolved, problems };
}

// Path A (pseudo-claims-purpose-harvest): mechanically harvest a group's PURPOSE
// from its comments, index-native, via the same digest builder `--comments-only`
// uses. Class group -> the class's comments; token group -> the namesake-token
// file's comments (else the group's key function). Written into the candidate
// `.lst` header at `--candidates` emit time so it is visible/prunable and travels
// with the group into drafting (where the label becomes the MECHANISM: hint).
const HARVEST_CAP = 700;
function harvestPurpose(index, label, members) {
  const commentsOf = (target) => {
    try {
      const d = index.buildDigest(target, { maxCallers: 0, maxCallees: 0, maxStrings: 0 });
      if (d && d.comments && d.comments.length) return [...d.comments].sort((a, b) => a.line - b.line);
    } catch (_) { /* target didn't resolve */ }
    return [];
  };
  const join = (cs) => cs.map((c) => c.text).join(' ').replace(/\s+/g, ' ').trim();
  // A file's LEADING comment block = its purpose header (catches // banners too).
  // Empty when nothing sits near the top (big multi-purpose files) -> caller falls back.
  const fileHeader = (file) => {
    const cs = commentsOf(file);
    if (!cs.length || cs[0].line > 8) return '';
    return join(cs.filter((c) => c.line <= 30));
  };
  const files = [...new Set((members || []).map((m) => m.file).filter(Boolean))];
  const primaryFile = (tok) => {
    if (tok) { const hit = files.find((f) => f.replace(/^.*\//, '').toLowerCase().includes(tok.toLowerCase())); if (hit) return hit; }
    return files.slice().sort((a, b) => members.filter((m) => m.file === b).length - members.filter((m) => m.file === a).length)[0] || null;
  };
  let purpose = '';
  const classM = (label || '').match(/^\[class\]\s+(\S+)/);
  if (classM) {
    const f = primaryFile(null);                        // the class's file -> its header
    purpose = (f && fileHeader(f)) || join(commentsOf(classM[1])); // else class-scope comments
  } else {
    const tokenM = (label || '').match(/^(\S+)\s*\(([^)]+)\)/);    // "token (namesakeFn) …"
    const token = tokenM ? tokenM[1] : '';
    const namesake = tokenM ? tokenM[2] : '';
    const f = primaryFile(token);                       // namesake-token file -> its header
    purpose = (f && fileHeader(f)) || (namesake ? join(commentsOf(namesake)) : '');
  }
  if (!purpose && members && members.length) purpose = join(commentsOf(members[0].bare || members[0].name));
  return purpose ? purpose.slice(0, HARVEST_CAP) : '';
}

// Assemble a bounded evidence pack from a group's resolved anchors.
function buildPack(resolved) {
  const packParts = [];
  let used = 0;
  let droppedForBudget = 0;
  const truncatedAnchors = [];
  for (const r of resolved) {
    if (used >= PACK_TOTAL_CHARS) { droppedForBudget++; continue; }
    let body = r.source;
    if (body.length > PACK_PER_ANCHOR_CHARS) {
      body = body.slice(0, PACK_PER_ANCHOR_CHARS) + '\n// … [truncated for evidence-pack budget]';
      truncatedAnchors.push(r.spec);
    }
    const header = `${r.filepath}@${r.name}  (L${r.start}-${r.end})`;
    const fence = fenceFor(body);
    packParts.push(`// ${header}\n${fence}\n${body}\n${fence}`);
    used += body.length;
  }
  return { pack: packParts.join('\n\n'), truncatedAnchors, droppedForBudget };
}

// --- Model drafting (the one non-deterministic step) -------------------------

// Parse the model's "CLAIM: … ANCHORS: - file@func — element" reply into
// { prose, anchors:[{file,func,line,element}] }. Ported from the prototype's
// parseGeneratedClaim. Tolerant of leading bullets, em/en/double-dash element
// separators, and a `()` suffix on function names.
export function parseGeneratedClaim(text) {
  const t = String(text || '');
  const claimM = t.match(/CLAIM:\s*([\s\S]*?)(?:\n\s*ANCHORS:|$)/i);
  const prose = (claimM ? claimM[1] : t.split(/ANCHORS:/i)[0]).trim().replace(/\s+/g, ' ');
  const anchorsBlock = t.split(/ANCHORS:/i)[1] || '';
  const anchors = [];
  for (const ln of anchorsBlock.split(/\r?\n/)) {
    const m = ln.match(/^[\s\-*]+(.+)$/);
    if (!m) continue;
    const parts = m[1].trim().split(/\s[—–-]\s|\s--\s/);
    const ref = (parts[0] || '').trim().replace(/[`'"]/g, '');
    const element = (parts.slice(1).join(' ') || '').trim();
    let file = ref, func = '', line = 0;
    const at = ref.split('@');
    if (at.length === 2) { file = at[0].trim(); func = at[1].trim().replace(/\(\)$/, ''); }
    else { const col = ref.match(/^(.+):(\d+)/); if (col) { file = col[1].trim(); line = Number(col[2]); } }
    if (file) anchors.push({ file, func, line, element });
  }
  return { prose, anchors };
}

// Grounding pass: keep only cited anchors whose function resolves to a real
// function in the index (a SEPARATE anti-fabrication control from the caveat —
// the caveat governs how cited code is characterized; grounding governs whether
// the citation exists). The kept anchor carries the index's resolved path/lines,
// not the model's (possibly hallucinated) spelling.
export function groundAnchors(index, anchors) {
  const grounded = [];
  const dropped = [];
  for (const a of anchors || []) {
    if (!a.func) { dropped.push({ ...a, reason: 'no function name to verify' }); continue; }
    const matches = index.findFunctionMatches(a.func, a.file || null);
    if (!matches || matches.length === 0) {
      dropped.push({ ...a, reason: 'cited function not found in index' });
      continue;
    }
    const m = matches[0];
    grounded.push({ file: m.filepath, func: m.name, start: m.start, end: m.end, element: a.element, ambiguous: matches.length > 1 });
  }
  return { grounded, dropped };
}

// Reusable CLAIM-CHART formatter (#284 --pseudo-claims-chart): render the claim
// AS WRITTEN — a preamble row plus one row per element/step of the claim prose
// (elements are semicolon-delimited; the drafter is instructed to write that
// way, so it works model-independently — Claude's coarse anchors or Gemini's
// fine ones alike). Each grounded anchor's cite is attached to the element whose
// text it most overlaps; elements with no confident cite are left blank
// (cite→element alignment is deliberately approximate for now). Kept
// standalone/exported so claim-search / claim-analyze can reuse the same
// element→evidence view rather than reinventing it.
export function formatClaimChart(prose, grounded) {
  const esc = (s) => String(s).replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
  const cite = (a) => `\`${a.file}@${a.func}\`${a.start ? ` (L${a.start}-${a.end})` : ''}`;
  const kw = (s) => new Set(String(s).toLowerCase().match(/[a-z][a-z0-9_]{3,}/g) || []);
  // Parse claim prose: preamble = text through the first ':'; elements = the
  // remainder split on ';' (standard method-claim form).
  const text = String(prose || '').trim();
  const ci = text.indexOf(':');
  const preamble = ci >= 0 ? text.slice(0, ci + 1).trim() : '';
  const body = ci >= 0 ? text.slice(ci + 1) : text;
  const elements = body.split(';').map((e) => e.trim().replace(/[.\s]+$/, '')).filter(Boolean);
  // Best-effort: attach each grounded cite to the element it most overlaps.
  const elemKw = elements.map(kw);
  const elemCites = elements.map(() => []);
  const unmatched = [];
  for (const a of grounded || []) {
    const aw = kw(a.element || '');
    let best = -1, score = 0;
    for (let i = 0; i < elemKw.length; i += 1) {
      let s = 0; for (const w of aw) if (elemKw[i].has(w)) s += 1;
      if (s > score) { score = s; best = i; }
    }
    const c = cite(a);
    if (best >= 0 && score >= 1) { if (!elemCites[best].includes(c)) elemCites[best].push(c); }
    else unmatched.push(c);
  }
  const lines = ['| # | Claim element / step | Cited code |', '|---|---|---|'];
  let n = 0;
  if (preamble) { n += 1; lines.push(`| ${n} | ${esc(preamble)} | _Preamble_ |`); }
  for (let i = 0; i < elements.length; i += 1) {
    n += 1;
    lines.push(`| ${n} | ${esc(elements[i])} | ${elemCites[i].join('<br>')} |`);
  }
  if (!preamble && !elements.length) lines.push('| — | _(no claim text to chart)_ | — |');
  if (unmatched.length) lines.push('', `_Grounded cite(s) not matched to a specific element: ${unmatched.join(', ')}._`);
  return lines;
}

/**
 * `--pseudo-claims --candidates <path>` (#284 B1): emit an UNRANKED mechanism
 * candidate anchors.lst via the deterministic grouper (mechanism-grouper.js),
 * instead of drafting. `--group-by concept` selects the token-only baseline;
 * `--file-seed` enables the opt-in residual file seed. `--ground-truth <gt.lst>`
 * scores the candidates' recall/precision against a hand-authored anchor set (a
 * dev path) instead of writing candidates. This is the front half of the pipeline
 * whose ranked one-command form is the future `--pseudo-claims --auto` (B2).
 */
export async function doEmitCandidates(index, args) {
  const indexName = String(args.index_path || '').replace(/[\\/]+$/, '').split(/[\\/]/).pop() || '?';
  let result;
  try {
    result = groupMechanisms(index, {
      indexName,
      mode: args.group_by === 'concept' ? 'concept' : 'multi',
      fileSeed: !!args.file_seed,
      useDocs: !!args.use_docs,
      catalogSeed: !!args.catalog_seed,
    });
  } catch (e) {
    console.error(`--pseudo-claims --candidates: grouping failed: ${e.message}`);
    process.exitCode = 1;
    return;
  }

  // --ground-truth: score instead of emit (dev path).
  if (args.ground_truth) {
    let gtText;
    try { gtText = fs.readFileSync(args.ground_truth, 'utf8'); }
    catch (e) { console.error(`--ground-truth: cannot read '${args.ground_truth}': ${e.message}`); process.exitCode = 1; return; }
    const s = scoreGrouping(index, result, gtText);
    console.log(`# mechanism-grouper score  index=${indexName}  group-by=${result.mode}  candidates=${result.groups.length} groups`);
    console.log(`# ground-truth: ${s.gtGroups} groups, ${s.scored} scored  avgRecall=${s.avgRecall.toFixed(2)} avgPrecision=${s.avgPrecision.toFixed(2)}`);
    for (const r of s.rows) {
      if (r.note) { console.log(`   ${r.label}: ${r.note}`); continue; }
      console.log(`   ${r.recall.toFixed(2)}R ${r.precision.toFixed(2)}P  ${r.together}/${r.resolved} together, in a cluster of ${r.clusterSize}  — ${r.label.slice(0, 58)}`);
    }
    return;
  }

  const outPath = (args.candidates && args.candidates !== '-' && args.candidates !== '.') ? args.candidates : null;

  // --rank (#284 ranker Phase 0): score each candidate with a bounded LLM
  // exploration-PRIORITY verdict, then emit the candidates ANNOTATED and sorted
  // highest-priority first. Still observe-only — the ANCHORS are identical; only
  // the `# ` headers gain a [P..] tag and the group order reflects priority.
  // Nothing is dropped or merged (that is Phase 1 / --auto). The pcrun soak
  // measures these verdicts.
  if (args.rank) {
    const model = resolveModel(args);
    if (!model || model.kind === 'error') {
      console.error(`--rank needs a model: pass --llm <provider> or --model <gguf> (${model?.error || 'none configured'}).`);
      process.exitCode = 1; return;
    }
    let drafter;
    try { drafter = makeDrafter(model, 0.2); }
    catch (e) { console.error(`--rank: ${e.message}`); process.exitCode = 1; return; }
    const mlabel = model.label || model.model || 'model';
    console.error(`# mechanism-ranker: scoring ${result.groups.length} candidates via ${mlabel}…`);
    const scored = await rankCandidates(result.groups, index, drafter, {});
    const vByLabel = new Map(scored.map((s) => [s.label, s.verdict]));
    const sorted = [...result.groups].sort((a, b) => ((vByLabel.get(b.label)?.priority ?? -1) - (vByLabel.get(a.label)?.priority ?? -1)));
    const ranked = scored.filter((s) => s.verdict).length;
    const caveat = [
      '# ILLUSTRATIVE claim-candidate ranking — a FAST, SURFACE heuristic to suggest where to',
      '# look FIRST, NOT legal analysis and NOT a judgment of novelty, importance, or worth.',
      '# A low P-score means only that a cluster RESEMBLES a common pattern or borrowed code at a',
      "# glance — NOT that it lacks value or novelty. Routine-looking code can be the crux, and",
      "# the user's considered judgment governs. Verify independently; not an admission about",
      '# any code or claim.',
      '#',
    ];
    const lines = [...caveat, `# mechanism-ranker  index=${indexName}  group-by=${result.mode}  ${result.groups.length} groups — RANKED by ${mlabel} (observe-only; anchors unchanged; ${ranked}/${scored.length} scored) — first-pass exploration priority; tag is [P0-3 signal/fold — what it resembles]`];
    for (const g of sorted) {
      const v = vByLabel.get(g.label);
      const tag = v ? `  [P${v.priority} ${v.signal}/${v.fold}${v.note ? ' — ' + v.note : ''}]` : '  [unscored]';
      const purpose = harvestPurpose(index, g.label, g.members);
      lines.push('', `# ${g.label}  (${g.members.length} fns)${tag}${purpose ? '  — ' + purpose : ''}`);
      for (const f of g.members) { const spec = f.name.includes('@') ? f.bare : f.name; lines.push(`${f.file}@${spec}`); }
    }
    const rankedText = lines.join('\n') + '\n';
    if (outPath) {
      fs.writeFileSync(outPath, rankedText, 'utf8');
      console.error(`# wrote ${result.groups.length} RANKED candidate group(s) to ${outPath}  (${indexName}, ${ranked}/${scored.length} scored by ${mlabel})`);
    } else {
      process.stdout.write(rankedText);
    }
    return;
  }

  const text = formatAnchors(result, { indexName, minComm: GROUPER_DEFAULTS.minComm, purposeFor: (label, members) => harvestPurpose(index, label, members) });
  if (outPath) {
    fs.writeFileSync(outPath, text, 'utf8');
    console.error(`# wrote ${result.groups.length} candidate group(s) to ${outPath}  (${indexName}, group-by=${result.mode}, unranked; pre-filtered ${result.noiseFiles} noise files / ${result.noiseFns} fns)`);
  } else {
    process.stdout.write(text);
  }
}

/**
 * Handle `--pseudo-claims <anchors>`. Partitions anchors into groups (one
 * pseudo-claim each), resolves + extracts each, assembles a bounded evidence
 * pack per group, then either prints the packs (--dry-run / no model) or drafts
 * one grounded pseudo-claim per pack. Sets process.exitCode on error.
 */
export async function doPseudoClaims(index, args) {
  if (args.candidates || args.ground_truth || args.rank) { await doEmitCandidates(index, args); return; }
  const spec = args.pseudo_claims;

  let groups;
  try {
    groups = collectAnchorGroups(spec);
  } catch (e) {
    console.error(`--pseudo-claims: could not read anchor list '${String(spec).slice(1)}': ${e.message}`);
    process.exitCode = 1;
    return;
  }
  if (groups.length === 0) {
    console.error('--pseudo-claims: no anchors given. Provide "file@func;file@func" or @anchors.lst (one file@func per line; "# Label" lines separate claims).');
    process.exitCode = 1;
    return;
  }

  const multi = groups.length > 1;

  // Resolve + pack each group.
  const sections = [];
  let totalResolved = 0;
  let totalProblems = 0;
  groups.forEach((g, gi) => {
    const { resolved, problems } = resolveGroup(index, g);
    const { pack, truncatedAnchors, droppedForBudget } = buildPack(resolved);
    sections.push({ label: g.label, purpose: g.purpose || '', groupNum: gi + 1, resolved, problems, pack, truncatedAnchors, droppedForBudget });
    totalResolved += resolved.length;
    totalProblems += problems.length;
  });

  // Report dropped anchors to stderr (grouped when there are multiple claims),
  // so stdout stays a clean artifact.
  if (totalProblems) {
    console.error(`\n${totalProblems} anchor(s) dropped (did not resolve to a real function):`);
    for (const s of sections) {
      if (!s.problems.length) continue;
      if (multi) console.error(`  [${s.label || `group ${s.groupNum}`}]`);
      for (const p of s.problems) console.error(`  ✗ ${p.spec} — ${p.reason}`);
    }
    console.error('');
  }
  if (totalResolved === 0) {
    console.error('--pseudo-claims: no anchors resolved to real functions; nothing to draft.');
    process.exitCode = 1;
    return;
  }

  const withAnchors = sections.filter((s) => s.resolved.length);
  const model = resolveModel(args);
  if (model && model.kind === 'error') {
    console.error(`--pseudo-claims: ${model.error}`);
    process.exitCode = 1;
    return;
  }
  const dryRun = !!args.dry_run || !model;
  // Evidence pack in the OUTPUT artifact: absent by default (keeps --pseudo-claims
  // lean); shown on --dry-run (the pack IS that mode's deliverable) or with
  // --include-evidence-pack. The model ALWAYS receives the pack as INPUT
  // (buildPack -> drafter, below) — this flag only controls the artifact.
  const showPack = dryRun || !!args.include_evidence_pack;
  const chartMode = !dryRun && !!args.pseudo_claims_chart;
  const temperature = args.temperature ?? 0;
  const modelDesc = !model ? '' : model.kind === 'gguf' ? `local GGUF ${model.modelPath}` : `${model.label} (${model.model})`;

  // If drafting, build the drafter up front (the air-gap gate + key check may
  // throw here).
  let drafter = null;
  if (!dryRun) {
    try {
      drafter = makeDrafter(model, temperature);
    } catch (e) {
      console.error(`--pseudo-claims: ${e.message}`);
      process.exitCode = 1;
      return;
    }
    process.stderr.write(`Drafting ${withAnchors.length} pseudo-claim(s) via ${modelDesc}…\n`);
  }

  // Draft each group's claim (sequentially; a shared GGUF session is not
  // concurrent-safe, and endpoints are gentler one at a time).
  const drafts = [];
  if (!dryRun) {
    for (let i = 0; i < withAnchors.length; i++) {
      const s = withAnchors[i];
      try {
        // Label + purpose as ONE line (separating them weakened both — the
        // ranker-purpose-signal lesson); triage annotations already stripped.
        const mech = s.label ? `${s.label}${s.purpose ? ' — ' + s.purpose : ''}` : '';
        const intent = mech ? `MECHANISM: ${mech}\n\n` : '';
        const raw = await drafter(PSEUDO_CLAIM_GENERATE_SYS, `${intent}CODE:\n${s.pack}`, 900);
        const { prose, anchors } = parseGeneratedClaim(raw);
        const { grounded, dropped } = groundAnchors(index, anchors);
        drafts.push({ prose, grounded, dropped });
        process.stderr.write(`  claim ${i + 1}/${withAnchors.length}: ${grounded.length} grounded anchor(s)${dropped.length ? `, ${dropped.length} ungrounded dropped` : ''}\n`);
      } catch (e) {
        drafts.push({ error: e.message });
        process.stderr.write(`  claim ${i + 1}/${withAnchors.length}: draft failed — ${e.message}\n`);
      }
    }
  }

  // Build the artifact: Block A once, then one section per non-empty group.
  const out = [];
  out.push(PSEUDO_CLAIM_CAVEAT_A);
  out.push('');
  if (dryRun) {
    out.push(`_Deterministic scaffold (dry run): below is the exact, size-capped evidence pack a model would be handed — one per pseudo-claim (${withAnchors.length}). To draft, pass \`--model <gguf>\` or set \`CE_OPENAI_API_URL\` (drop \`--dry-run\`)._`);
  } else {
    out.push(`_Drafted from ${withAnchors.length} evidence pack(s) via ${modelDesc}. Each claim's cited anchors are **grounded** — verified to resolve to a real function in the index; ungrounded citations are dropped.${showPack ? ' The evidence pack the draft was grounded in follows each claim.' : ' Pass --include-evidence-pack to append each claim\'s evidence pack.'}_`);
  }
  out.push('');

  withAnchors.forEach((s, i) => {
    const label = s.label ? ` — ${s.label}` : '';
    out.push(`## Pseudo-claim ${i + 1}${label}`);
    out.push('');

    if (!dryRun) {
      const d = drafts[i];
      out.push(PSEUDO_CLAIM_CAVEAT_B);
      out.push('');
      if (d.error) {
        out.push(`_Draft failed: ${d.error}. The evidence pack is below for reference._`);
        out.push('');
      } else {
        out.push(d.prose || '_(model produced no claim text)_');
        out.push('');
        if (chartMode) {
          out.push(`### Claim chart (${d.grounded.length} grounded cite${d.grounded.length === 1 ? '' : 's'}${d.dropped.length ? `, ${d.dropped.length} ungrounded dropped` : ''})`);
          out.push('');
          for (const ln of formatClaimChart(d.prose, d.grounded)) out.push(ln);
        } else {
          out.push(`### Cited anchors (${d.grounded.length} grounded${d.dropped.length ? `, ${d.dropped.length} ungrounded dropped` : ''})`);
          out.push('');
          for (const a of d.grounded) {
            out.push(`- \`${a.file}@${a.func}\` — L${a.start}-${a.end}${a.element ? ` — ${a.element}` : ''}`);
          }
          if (!d.grounded.length) out.push('- _(no cited anchor resolved to a real function)_');
        }
        if (d.dropped.length) {
          out.push('');
          out.push(`_Dropped (cited but not found in index): ${d.dropped.map((a) => `\`${a.file}@${a.func || '?'}\``).join(', ')}._`);
        }
        out.push('');
      }
      if (showPack) out.push('### Evidence pack (the code this draft was grounded in)');
    } else {
      out.push(`### Anchors (${s.resolved.length})`);
      out.push('');
      for (const a of s.resolved) {
        out.push(`- \`${a.filepath}@${a.name}\` — L${a.start}-${a.end} (${a.end - a.start + 1} lines)`);
      }
      if (showPack) out.push('', '### Evidence pack');
    }

    if (showPack) {
      out.push('');
      if (s.truncatedAnchors.length) {
        out.push(`_Truncated to the ${PACK_PER_ANCHOR_CHARS}-char per-anchor cap: ${s.truncatedAnchors.map((x) => `\`${x}\``).join(', ')}._`);
        out.push('');
      }
      if (s.droppedForBudget) {
        out.push(`_${s.droppedForBudget} anchor(s) omitted after the ${PACK_TOTAL_CHARS}-char per-claim pack budget was reached._`);
        out.push('');
      }
      out.push(s.pack);
      out.push('');
    }
  });
  out.push(PSEUDO_CLAIM_CAVEAT_C);

  const text = out.join('\n') + '\n';

  // Emit to stdout or --pseudo-out <file>.
  if (args.pseudo_out) {
    try {
      fs.writeFileSync(args.pseudo_out, text, 'utf8');
      console.log(`Wrote pseudo-claims artifact to ${args.pseudo_out} — ${withAnchors.length} pseudo-claim(s), ${totalResolved} anchor(s)${totalProblems ? `, ${totalProblems} dropped` : ''}${dryRun ? ' (dry run — no model draft)' : ''}.`);
    } catch (e) {
      console.error(`--pseudo-claims: could not write '${args.pseudo_out}': ${e.message}`);
      process.exitCode = 1;
    }
  } else {
    process.stdout.write(text);
  }
}
