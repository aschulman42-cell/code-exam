// A fence longer than the longest backtick run in `body` — CE's own source is
// full of backtick template literals, so a fixed ``` fence would break out of
// the block mid-body.
function fenceFor(body) {
  const longest = (String(body).match(/`+/g) || []).reduce((n, s) => Math.max(n, s.length), 0);
  return '`'.repeat(Math.max(3, longest + 1));
}

// Partition the command value into anchor GROUPS (one group == one pseudo-claim).
//   - inline "a@f;b@g"  -> a single group (label null)
//   - "@anchors.lst"    -> one-or-more groups; a "# Label" line starts a new
//                          group and names it; anchors before any header form an
//                          implicit first group; blank lines ignored.
// Headers are parsed via parseAnchorHeader (the grouper emit's inverse), so a
// group carries a CLEAN {label, priority, purpose} — the `(N fns)` count,
// `[P…]` priority tag, and ranker note are stripped rather than riding into
// the MECHANISM hint and the output heading. The hint itself is KEPT (label +
// purpose); only the triage annotations are removed. Priority never reaches
// the drafter — its one consumer is the --min-rank draft filter. Exported for
// tests.
export function collectAnchorGroups(spec) {
  if (!spec || !spec.startsWith('@')) {
    const specs = String(spec || '').split(';').map((s) => s.trim()).filter(Boolean);
    return specs.length ? [{ label: null, priority: null, fold: null, purpose: '', specs }] : [];
  }
  const listPath = spec.slice(1);
  const text = fs.readFileSync(listPath, 'utf8'); // caller catches ENOENT
  const groups = [];
  let cur = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith('#')) {
      const { label, priority, fold, purpose } = parseAnchorHeader(line);
      cur = { label: label || null, priority: priority ?? null, fold: fold ?? null, purpose: purpose || '', specs: [] };
      groups.push(cur);
      continue;
    }
    if (!cur) { cur = { label: null, priority: null, fold: null, purpose: '', specs: [] }; groups.push(cur); }
    cur.specs.push(line);
  }
  return groups.filter((g) => g.specs.length);
}

// #291 Part B: pack-budget omissions must be visible in the LEAN artifact too
// (the --min-rank disclosure principle applied to evidence packs) — a claim
// drafted from 8 of a group's 121 anchors silently presenting itself as the
// whole group is how Bram pseudo-claim 1 happened. Exported for tests.
export function packDisclosure(s) {
  const dropped = s.droppedForBudget || 0;
  const truncated = (s.truncatedAnchors || []).length;
  if (!dropped && !truncated) return '';
  const total = (s.resolved || []).length;
  const bits = [`packed ${total - dropped} of ${total} resolved anchor(s)`];
  if (dropped) bits.push(`${dropped} omitted for the pack budget`);
  if (truncated) bits.push(`${truncated} truncated`);
  return `_Evidence pack: ${bits.join('; ')}._`;
}

// issue-286-doc-line-anchors: `path@L<start>[-<end>]` is a LINE-RANGE anchor,
// valid on ANY indexed file — which is what lets DOCUMENTATION be cited as
// evidence (patent practice cites manuals and printed publications alongside
// code; CE's --use-docs experiment (de47d0b) established the term-vote channel
// is the wrong way to use docs while this evidence channel was unbuilt).
// Parsed HERE, not in the shared parseFuncSpec — the draft pipeline is the
// only consumer; #286's cross-command @line normalization stays open.
// Exported for tests.
export function parseLineAnchor(spec) {
  const m = String(spec || '').trim().match(/^(.+)@L(\d+)(?:-(\d+))?$/);
  if (!m) return null;
  const start = Number(m[2]);
  const end = m[3] ? Number(m[3]) : start;
  if (start < 1 || end < start) return null;
  return { file: m[1].trim(), start, end };
}

// Resolve a (possibly suffix-abbreviated) path against the index's fileLines:
// exact key first, else a UNIQUE suffix match (slash-normalized). Returns the
// indexed key, null on miss, or { ambiguous: true } — a doc cite must resolve
// to exactly one indexed file, same anti-fabrication posture as functions.
function resolveIndexedFile(index, p) {
  const fl = index.fileLines;
  if (!fl || typeof fl.get !== 'function') return null;
  if (fl.has(p)) return p;
  const norm = String(p).replace(/\\/g, '/');
  let hit = null, count = 0;
  for (const key of fl.keys()) {
    const k = String(key).replace(/\\/g, '/');
    if (k === norm || k.endsWith('/' + norm)) { hit = key; count++; if (count > 1) return { ambiguous: true }; }
  }
  return count === 1 ? hit : null;
}

// Resolve one group's anchor specs to real functions (the existence check the
// file-level prototype lacked — it cited fragments like strRe.exec(body)) —
// or, for `path@L<start>-<end>` specs, to line-range excerpts of any indexed
// file (issue-286-doc-line-anchors).
function resolveGroup(index, group) {
  const resolved = [];
  const problems = [];
  for (const a of group.specs) {
    const la = parseLineAnchor(a);
    if (la) {
      const hit = resolveIndexedFile(index, la.file);
      if (!hit || hit.ambiguous) {
        problems.push({ spec: a, reason: hit && hit.ambiguous ? 'line-anchor path is ambiguous in the index — use a longer suffix' : 'line-anchor file is not in the index' });
        continue;
      }
      const lines = index.fileLines.get(hit) || [];
      if (la.start > lines.length) {
        problems.push({ spec: a, reason: `line range starts past end of file (${lines.length} lines)` });
        continue;
      }
      const end = Math.min(la.end, lines.length);
      const source = lines.slice(la.start - 1, end).join('\n');
      if (!source.trim()) { problems.push({ spec: a, reason: 'line range is empty' }); continue; }
      resolved.push({ spec: a, filepath: hit, name: `L${la.start}-${end}`, start: la.start, end, source, kind: 'lines' });
      continue;
    }
    const { fileHint, funcName } = parseFuncSpec(a);
    const matches = index.findFunctionMatches(funcName, fileHint);
    if (!matches || matches.length === 0) {
      problems.push({ spec: a, reason: 'no function in the index resolves to this anchor' });
      continue;
    }
    if (matches.length > 1) {
      const opts = matches.slice(0, 5).map((m) => `${m.filepath}@${m.name} (L${m.start}-${m.end})`).join('; ');
      const more = matches.length > 5 ? `; …+${matches.length - 5} more` : '';
      problems.push({ spec: a, reason: `ambiguous — ${matches.length} functions match; use an exact file@func (e.g. ${opts}${more})` });
      continue;
    }
    const m = matches[0];
    const source = index.getFunctionSource(m.filepath, m.name);
    if (!source) {
      problems.push({ spec: a, reason: 'matched, but source could not be extracted (file content not loaded in this index)' });
      continue;
    }
    resolved.push({ spec: a, filepath: m.filepath, name: m.name, start: m.start, end: m.end, source });
  }
  return { resolved, problems };
}

// Path A (pseudo-claims-purpose-harvest): mechanically harvest a group's PURPOSE
// from its comments, index-native, via the same digest builder `--comments-only`
// uses. Class group -> the class's comments; token group -> the namesake-token
// file's comments (else the group's key function). Written into the candidate
// `.lst` header at `--candidates` emit time so it is visible/prunable and travels
// with the group into drafting (where the label becomes the MECHANISM: hint).
const HARVEST_CAP = 700;
function harvestPurpose(index, label, members) {
  const commentsOf = (target) => {
    try {
      const d = index.buildDigest(target, { maxCallers: 0, maxCallees: 0, maxStrings: 0 });
      if (d && d.comments && d.comments.length) return [...d.comments].sort((a, b) => a.line - b.line);
    } catch (_) { /* target didn't resolve */ }
    return [];
  };
  const join = (cs) => cs.map((c) => c.text).join(' ').replace(/\s+/g, ' ').trim();
  // A file's LEADING comment block = its purpose header (catches // banners too).
  // Empty when nothing sits near the top (big multi-purpose files) -> caller falls back.
  const fileHeader = (file) => {
    const cs = commentsOf(file);
    if (!cs.length || cs[0].line > 8) return '';
    return join(cs.filter((c) => c.line <= 30));
  };
  const files = [...new Set((members || []).map((m) => m.file).filter(Boolean))];
  const primaryFile = (tok) => {
    if (tok) { const hit = files.find((f) => f.replace(/^.*\//, '').toLowerCase().includes(tok.toLowerCase())); if (hit) return hit; }
    return files.slice().sort((a, b) => members.filter((m) => m.file === b).length - members.filter((m) => m.file === a).length)[0] || null;
  };
  let purpose = '';
  const classM = (label || '').match(/^\[class\]\s+(\S+)/);
  if (classM) {
    const f = primaryFile(null);                        // the class's file -> its header
    purpose = (f && fileHeader(f)) || join(commentsOf(classM[1])); // else class-scope comments
  } else {
    const tokenM = (label || '').match(/^(\S+)\s*\(([^)]+)\)/);    // "token (namesakeFn) …"
    const token = tokenM ? tokenM[1] : '';
    const namesake = tokenM ? tokenM[2] : '';
    const f = primaryFile(token);                       // namesake-token file -> its header
    purpose = (f && fileHeader(f)) || (namesake ? join(commentsOf(namesake)) : '');
  }
  if (!purpose && members && members.length) purpose = join(commentsOf(members[0].bare || members[0].name));
  return purpose ? purpose.slice(0, HARVEST_CAP) : '';
}

// --min-rank (pseudo-claims-min-rank): user-controlled draft-time floor over
// the [P..] tags parseAnchorHeader surfaces. Selection happens at CONSUMPTION
// so the ranked .lst stays a complete, auditable artifact. Default is P2 —
// but only when the list actually carries rank tags (an unranked list drafts
// everything; no silent surprise). Untagged/[unscored] groups always draft
// (can't judge -> don't silently drop). The ranker's tags remain observe-only
// annotations under their caveat block; the filter is the USER'S explicit
// instruction (or an overridable default), which keeps CE out of worthiness
// opinions. Exported for tests.
export function parseMinRank(v) {
  if (v == null || v === '') return null;
  const m = String(v).trim().match(/^[pP]?([0-3])$/);
  return m ? Number(m[1]) : NaN;
}

export function filterGroupsByMinRank(groups, minRankValue) {
  const floor = parseMinRank(minRankValue);
  const tagged = groups.some((g) => g.priority != null);
  const effective = floor != null ? floor : (tagged ? 2 : null);
  if (effective == null || effective === 0) return { groups, floor: effective, dropped: 0, tagged };
  const kept = groups.filter((g) => g.priority == null || g.priority >= effective);
  return { groups: kept, floor: effective, dropped: groups.length - kept.length, tagged };
}

// chart-toc-rank-display: the claim's own PREAMBLE clause (text up to the
// first ':') is its best human-readable name — grouper labels like
// `[file] json-stream.js` say where a claim came from, not what it is about.
// Exported for tests.
export function claimPreambleSnippet(prose, max = 90) {
  const text = String(prose || '').trim();
  if (!text) return '';
  const ci = text.indexOf(':');
  let pre = (ci > 0 ? text.slice(0, ci) : text).replace(/\s+/g, ' ').trim();
  if (pre.length > max) pre = pre.slice(0, max - 1).trimEnd() + '…';
  return pre;
}

// chart-toc-rank-display: table-of-contents lines for a multi-claim chart —
// rank + grouper label + preamble snippet. Tool-emitted AFTER drafting, so
// (like the heading rank suffix) nothing here ever reaches the model and the
// MECHANISM hint stays clean. Exported for tests.
export function formatChartToc(rows) {
  const out = ['## Contents', ''];
  for (const r of rows) {
    const rank = r.priority != null ? `[P${r.priority}] ` : '';
    // grouper-echo-flag-fold: the smaller group of an echo pair flags toward
    // its larger host so TOC scanning surfaces probable duplicates.
    const echo = r.echoOf ? ` — likely echo of #${r.echoOf.hostN} ${r.echoOf.hostLabel}` : '';
    out.push(`${r.n}. ${rank}${r.label || '(unlabeled)'}${r.preamble ? ` — "${r.preamble}"` : ''}${echo}`);
  }
  out.push('');
  return out;
}

// Assemble a bounded evidence pack from a group's resolved anchors.
function buildPack(resolved) {
  const packParts = [];
  let used = 0;
  let droppedForBudget = 0;
  const truncatedAnchors = [];
  for (const r of resolved) {
    if (used >= PACK_TOTAL_CHARS) { droppedForBudget++; continue; }
    let body = r.source;
    if (body.length > PACK_PER_ANCHOR_CHARS) {
      body = body.slice(0, PACK_PER_ANCHOR_CHARS) + '\n// … [truncated for evidence-pack budget]';
      truncatedAnchors.push(r.spec);
    }
    const header = r.kind === 'lines'
      ? `${r.filepath}@L${r.start}-${r.end}  (documentation excerpt)`
      : `${r.filepath}@${r.name}  (L${r.start}-${r.end})`;
    const fence = fenceFor(body);
    packParts.push(`// ${header}\n${fence}\n${body}\n${fence}`);
    used += body.length;
  }
  return { pack: packParts.join('\n\n'), truncatedAnchors, droppedForBudget };
}

